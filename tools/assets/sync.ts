// Installs the SMRT Speech visual asset pack into the app.
//
//   npx tsx tools/assets/sync.ts        (npm run assets)
//
// 1. Copies the pack's SVG artwork, app icons and app-shell backgrounds to public/smrt-assets/,
//    keeping the pack's relative paths, and checks every file against the pack's manifest.
// 2. Writes src/ui/smrt-icons.ts: the line drawing inside each manifest icon, with its stroke
//    colour replaced by currentColor, so interface icons follow the light and dark themes.
//    The geometry is taken from the pack unchanged.
// 3. Writes the maskable home-screen icon from branding/app-icon.svg (the same artwork on a
//    full square, as Android and iPadOS masks need).
import sharp from 'sharp';
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const PACK = ROOT + 'SMRT_Speech_Visual_Asset_Pack/SMRT_Speech_Visual_Asset_Pack/';
const OUT = ROOT + 'public/smrt-assets/';

interface Asset {
  id: string;
  svg: string;
  png: string;
  jpeg: string;
  role: string;
  glyph: string;
}

const manifest = JSON.parse(readFileSync(PACK + 'integration/ASSET_MANIFEST.json', 'utf8')) as { version: string; assets: Asset[] };
const missing: string[] = [];
const copied: string[] = [];

function copy(rel: string) {
  if (!existsSync(PACK + rel)) {
    missing.push(rel);
    return;
  }
  mkdirSync(dirname(OUT + rel), { recursive: true });
  copyFileSync(PACK + rel, OUT + rel);
  copied.push(rel);
}

rmSync(OUT, { recursive: true, force: true });

// Every manifest icon as SVG (the preferred format), plus the files outside the manifest list.
for (const a of manifest.assets) copy(a.svg);
for (const f of readdirSync(PACK + 'ui/frames')) if (f.endsWith('.svg')) copy('ui/frames/' + f);
for (const f of ['app-icon.svg', 'app-icon-180.png', 'app-icon-192.png', 'app-icon-512.png']) copy('branding/' + f);
// The decorative backgrounds are for the app shell only. The therapy canvas stays flat white,
// so the pack's therapy-*.jpg files are deliberately not installed.
for (const f of ['light.jpg', 'dark.jpg']) copy('backgrounds/' + f);

if (missing.length > 0) {
  console.error('Missing from the pack:\n  ' + missing.join('\n  '));
  process.exit(1);
}

// ---- Inline glyphs --------------------------------------------------------------------------
const BACKING = /<rect width="100" height="100" rx="20" fill="#FAF5F2"\/>/;
const glyphs: Record<string, string> = {};
for (const a of manifest.assets) {
  const svg = readFileSync(PACK + a.svg, 'utf8');
  if (!/viewBox="0 0 100 100"/.test(svg)) throw new Error(`${a.svg}: unexpected viewBox`);
  const inner = svg
    .replace(/^<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(BACKING, '')
    .replace(/stroke="#[0-9A-Fa-f]{6}"/g, 'stroke="currentColor"')
    .trim();
  if (/#[0-9A-Fa-f]{6}/.test(inner)) throw new Error(`${a.svg}: a fixed colour is left in the glyph`);
  glyphs[a.svg.replace(/\.svg$/, '')] = inner;
}

const lines = [
  '// GENERATED by tools/assets/sync.ts from SMRT_Speech_Visual_Asset_Pack. Do not edit by hand.',
  '// Each entry is the line drawing of one pack icon (100 x 100 grid), stroke set to currentColor.',
  `export const SMRT_ASSET_VERSION = ${JSON.stringify(manifest.version)};`,
  '',
  'export const SMRT_GLYPHS = {',
  ...Object.entries(glyphs).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`),
  '} as const;',
  '',
  'export type SmrtGlyph = keyof typeof SMRT_GLYPHS;',
  '',
  '/** Every file installed under public/smrt-assets/, for checks and offline verification. */',
  'export const SMRT_ASSET_FILES: readonly string[] = [',
  ...copied.sort().map((f) => `  ${JSON.stringify(f)},`),
  '];',
  '',
];
writeFileSync(ROOT + 'src/ui/smrt-icons.ts', lines.join('\n'));

// ---- Maskable icon --------------------------------------------------------------------------
const brand = readFileSync(PACK + 'branding/app-icon.svg', 'utf8').replace('rx="110"', 'rx="0"');
mkdirSync(ROOT + 'public/icons', { recursive: true });
const art = await sharp(Buffer.from(brand), { density: 300 }).resize(512, 512).png().toBuffer();
await sharp(art).toFile(ROOT + 'public/icons/icon-maskable-512.png');

console.log(`Installed ${copied.length} files to public/smrt-assets/ and ${Object.keys(glyphs).length} glyphs to src/ui/smrt-icons.ts`);
